"""Run one annotator as a bounded Codex app-server task.

Protocol: JSON-RPC 2.0 over newline-delimited JSON on the app server's stdio
(``codex app-server``). The runner:

1. ``initialize`` with ``experimentalApi`` so dynamic tools are available;
2. ``thread/start`` in the read-only workspace with ``approvalPolicy: never``,
   ``sandbox: read-only``, an ephemeral thread, and the trace-inspection tools
   registered as *dynamic tools* (served back to Codex by this process);
3. ``turn/start`` with the sealed instructions as the only input and the
   proposal JSON Schema as ``outputSchema``;
4. answers every ``item/tool/call`` by dispatching to ``TraceInspectionTools``,
   declines every approval request, and interrupts the turn on any limit;
5. takes the final ``agentMessage`` text as the proposal.

Hidden reasoning is never requested: reasoning deltas are ignored and never
persisted. Only the structured output, tool calls, and token usage survive.

``AppServerTransport`` is a small protocol so the same runner logic runs
against a scripted in-process fake in tests without a Codex binary.
"""

